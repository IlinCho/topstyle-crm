#!/usr/bin/env node
/**
 * Creates the full topstyle.bg category tree (all top-level categories and
 * their subcategories) in the live Neon/Postgres database, AND generates a
 * matching MySQL SQL file for the php-site version.
 *
 * Why this exists: an earlier session wrote SQL scripts to add the missing
 * subcategories (e.g. "Пролетни" / "Есенно-зимни" under "Мъжки якета") but
 * they were only ever downloaded, never actually run against the live
 * database - so those categories never existed, and scripts/prestashop-import/
 * import.mjs has been silently SKIPPING every product whose only real
 * category link was one of those missing subcategories (see skippedNoCategory
 * in that script). This script fixes that at the root: creates every
 * category up front, in the right parent/child structure and the right
 * display order, so a subsequent run of import.mjs can file those products
 * correctly instead of dropping them.
 *
 * RUN (in order):
 *   node scripts/prestashop-import/create-categories.mjs
 *   node scripts/prestashop-import/import.mjs        <- re-run AFTER this,
 *                                                        so the newly-created
 *                                                        categories actually
 *                                                        pick up products.
 *
 * Safe to re-run any time - categories are upserted by slug (name, position,
 * and parent are reset to the canonical values below on every run; nothing
 * is deleted).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { randomUUID } from "node:crypto";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, "..", "..");
const OUT_SQL = path.join(__dirname, "mysql-categories.sql");

function loadEnvFile() {
  const envPath = path.join(PROJECT_ROOT, ".env");
  if (!fs.existsSync(envPath)) return;
  const text = fs.readFileSync(envPath, "utf8");
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}
loadEnvFile();

const { PrismaClient } = await import("@prisma/client");
const prisma = new PrismaClient();

// The full topstyle.bg category tree, in the exact order it appears in the
// site's own navigation. `parentSlug: null` = top-level category.
const CATEGORIES = [
  { slug: "mazhki-teniski", name: "Мъжки тениски", parentSlug: null },
  { slug: "teniski-s-yaka", name: "Тениски с яка", parentSlug: "mazhki-teniski" },

  { slug: "mzhki-yaketa", name: "Мъжки якета", parentSlug: null },
  { slug: "proletni", name: "Пролетни", parentSlug: "mzhki-yaketa" },
  { slug: "esenno-zimni", name: "Есенно-зимни", parentSlug: "mzhki-yaketa" },

  { slug: "myzhki-ekipi", name: "Мъжки екипи", parentSlug: null },
  { slug: "ekipi", name: "Екипи", parentSlug: "myzhki-ekipi" },
  { slug: "suicheri", name: "Суичери", parentSlug: "myzhki-ekipi" },
  { slug: "dolnishte", name: "Долнище", parentSlug: "myzhki-ekipi" },

  { slug: "myzhki-dynki-i-pantaloni", name: "Мъжки дънки и панталони", parentSlug: null },
  { slug: "kysi-dynki", name: "Къси дънки", parentSlug: "myzhki-dynki-i-pantaloni" },
  { slug: "kysi-pantaloni", name: "Къси панталони", parentSlug: "myzhki-dynki-i-pantaloni" },

  { slug: "myzhki-bluzi", name: "Мъжки блузи", parentSlug: null },
  { slug: "puloveri", name: "Пуловери", parentSlug: "myzhki-bluzi" },
  { slug: "hudi", name: "Худи", parentSlug: "myzhki-bluzi" },

  { slug: "myzhki-rizi", name: "Мъжки ризи", parentSlug: null },
  { slug: "banski", name: "Бански", parentSlug: null },
  { slug: "komplekti", name: "Комплекти", parentSlug: null },
];

function mysqlId() {
  return randomUUID().replace(/-/g, "");
}
function sqlStr(v) {
  if (v === null || v === undefined) return "NULL";
  return `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

async function main() {
  console.log(`Creating/updating ${CATEGORIES.length} categories...`);

  let created = 0;
  let updated = 0;
  const sql = [
    "-- Generated by scripts/prestashop-import/create-categories.mjs - safe to re-run.",
    "SET NAMES utf8mb4;",
    "",
  ];

  // Two passes: top-level categories first (so subcategories can look up
  // their parent's id), then subcategories.
  for (const pass of [(c) => !c.parentSlug, (c) => !!c.parentSlug]) {
    for (const [index, cat] of CATEGORIES.entries()) {
      if (!pass(cat)) continue;

      let parentId = null;
      let parentSlugForSql = null;
      if (cat.parentSlug) {
        const parent = await prisma.category.findUnique({ where: { slug: cat.parentSlug } });
        if (!parent) {
          console.warn(`  Skipping "${cat.name}" - parent category "${cat.parentSlug}" not found (shouldn't happen).`);
          continue;
        }
        parentId = parent.id;
        parentSlugForSql = cat.parentSlug;
      }

      const existing = await prisma.category.findUnique({ where: { slug: cat.slug } });
      if (existing) {
        await prisma.category.update({
          where: { slug: cat.slug },
          data: { name: cat.name, position: index, parentId },
        });
        updated++;
      } else {
        await prisma.category.create({
          data: { slug: cat.slug, name: cat.name, position: index, parentId },
        });
        created++;
        console.log(`  + created "${cat.name}" (${cat.slug})${cat.parentSlug ? ` under ${cat.parentSlug}` : ""}`);
      }

      const newId = mysqlId();
      sql.push(
        `INSERT INTO category (id, slug, name, position, parent_id) VALUES ` +
          `(${sqlStr(newId)}, ${sqlStr(cat.slug)}, ${sqlStr(cat.name)}, ${index}, ` +
          `${parentSlugForSql ? `(SELECT id FROM category WHERE slug = ${sqlStr(parentSlugForSql)})` : "NULL"}) ` +
          `ON DUPLICATE KEY UPDATE name = VALUES(name), position = VALUES(position), parent_id = VALUES(parent_id);`
      );
    }
  }

  fs.writeFileSync(OUT_SQL, sql.join("\n"), "utf8");
  console.log(`\nDone. ${created} created, ${updated} already existed (name/position/parent refreshed).`);
  console.log(`MySQL file written to: ${OUT_SQL}`);
  console.log(`\nNext step: re-run "node scripts/prestashop-import/import.mjs" so products that`);
  console.log(`only had a link to one of these (previously missing) subcategories get imported.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
