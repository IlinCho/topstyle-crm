#!/usr/bin/env node
/**
 * Exports the CURRENT live catalog (categories + products + variants +
 * images + reviews) from the real Neon/Postgres database into a ready-to-run
 * MySQL file for the php-site/ version.
 *
 * Unlike mysql-import.sql (a one-time, now-stale snapshot generated from the
 * original PrestaShop CSV export back on 2026-08-24), this script reads
 * straight from the live Next.js admin database, so it picks up every
 * product/category/price/stock change made through Admin since then -
 * including brand new products added after the original migration.
 *
 * Run this any time before a fresh MySQL import (e.g. right before the
 * Jump.bg test, and again right before the real cutover) to make sure
 * php-site's catalog matches what's actually live on topstyle-crm.vercel.app.
 *
 * Reuses the *same* ids Postgres already generated (Prisma's cuid() output
 * is well under MySQL's VARCHAR(32) column limit here), so products/
 * categories/variants/images link up correctly without any slug/SKU
 * subquery lookups - just a straight id-for-id copy.
 *
 * RUN (from the project root, in Terminal):
 *   node scripts/prestashop-import/export-to-mysql.mjs
 *
 * Output: php-site/mysql-data-export.sql - import this via cPanel ->
 * phpMyAdmin -> your database -> Import, any time AFTER schema.sql has
 * already been imported once. Safe to re-run/re-import repeatedly - every
 * statement is an upsert (ON DUPLICATE KEY UPDATE / DELETE+re-INSERT for
 * variants+images / INSERT IGNORE for reviews), so importing it again after
 * more changes just brings MySQL back in sync, without duplicating rows.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, "..", "..");
const OUT_SQL = path.join(PROJECT_ROOT, "php-site", "mysql-data-export.sql");

// Plain `node script.mjs` doesn't auto-load .env like Next.js/Prisma CLI do -
// load it ourselves, same as import.mjs.
function loadEnvFile() {
  const envPath = path.join(PROJECT_ROOT, ".env");
  if (!fs.existsSync(envPath)) return;
  const text = fs.readFileSync(envPath, "utf8");
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}
loadEnvFile();

const { PrismaClient } = await import("@prisma/client");
const prisma = new PrismaClient();

function sqlStr(v) {
  return `'${String(v ?? "").replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}
function sqlNum(v) {
  return v === null || v === undefined ? "NULL" : String(v);
}
function sqlBool(v) {
  return v ? "1" : "0";
}
function sqlNullableId(v) {
  return v ? sqlStr(v) : "NULL";
}

async function main() {
  const categories = await prisma.category.findMany();
  const products = await prisma.product.findMany({
    include: { variants: true, images: { orderBy: { position: "asc" } }, reviews: true },
  });

  const sql = [];
  sql.push("-- Generated by scripts/prestashop-import/export-to-mysql.mjs - safe to re-run/re-import.");
  sql.push(`-- Snapshot of the live Neon catalog as of ${new Date().toISOString()}.`);
  sql.push("SET NAMES utf8mb4;");
  sql.push("SET FOREIGN_KEY_CHECKS = 0;");
  sql.push("");

  // ---- Categories - pass 1: insert every row with parent_id left NULL, so
  // a child category's FK to its parent never fails just because of
  // whichever order Prisma happened to return rows in. ----
  sql.push("-- Categories (pass 1: no parent_id yet, to avoid FK-order issues)");
  for (const c of categories) {
    sql.push(
      `INSERT INTO category (id, slug, name, position, parent_id, image_url, home_tile_title) VALUES (${sqlStr(c.id)}, ${sqlStr(c.slug)}, ${sqlStr(c.name)}, ${sqlNum(c.position)}, NULL, ${sqlStr(c.imageUrl)}, ${sqlStr(c.homeTileTitle)}) ` +
      `ON DUPLICATE KEY UPDATE name=VALUES(name), position=VALUES(position), image_url=VALUES(image_url), home_tile_title=VALUES(home_tile_title);`
    );
  }
  sql.push("");
  sql.push("-- Categories (pass 2: now link up subcategories to their parent)");
  for (const c of categories) {
    if (c.parentId) {
      sql.push(`UPDATE category SET parent_id = ${sqlStr(c.parentId)} WHERE id = ${sqlStr(c.id)};`);
    }
  }
  sql.push("");

  // ---- Products + variants + images ----
  sql.push("-- Products");
  for (const p of products) {
    sql.push(
      `INSERT INTO product (id, sku, name, slug, description, material, color, price_eur, price_bgn, active, category_rank, badges, size_chart_url, size_chart_note, size_chart_table, category_id) VALUES (` +
      `${sqlStr(p.id)}, ${sqlStr(p.sku)}, ${sqlStr(p.name)}, ${sqlStr(p.slug)}, ${sqlStr(p.description)}, ${sqlStr(p.material)}, ${sqlStr(p.color)}, ${sqlNum(p.priceEur)}, ${sqlNum(p.priceBgn)}, ${sqlBool(p.active)}, ${sqlNum(p.categoryRank)}, ${sqlStr(p.badges)}, ${sqlStr(p.sizeChartUrl)}, ${sqlStr(p.sizeChartNote)}, ${sqlStr(p.sizeChartTable)}, ${sqlStr(p.categoryId)}` +
      `) ON DUPLICATE KEY UPDATE name=VALUES(name), slug=VALUES(slug), description=VALUES(description), material=VALUES(material), color=VALUES(color), price_eur=VALUES(price_eur), price_bgn=VALUES(price_bgn), active=VALUES(active), category_rank=VALUES(category_rank), badges=VALUES(badges), size_chart_url=VALUES(size_chart_url), size_chart_note=VALUES(size_chart_note), size_chart_table=VALUES(size_chart_table), category_id=VALUES(category_id);`
    );

    sql.push(`DELETE FROM product_variant WHERE product_id = ${sqlStr(p.id)};`);
    if (p.variants.length > 0) {
      const rows = p.variants.map(
        (v) => `(${sqlStr(v.id)}, ${sqlStr(p.id)}, ${sqlStr(v.size)}, ${sqlStr(v.color)}, ${sqlNum(v.stock)})`
      );
      sql.push(`INSERT INTO product_variant (id, product_id, size, color, stock) VALUES\n  ${rows.join(",\n  ")};`);
    }

    sql.push(`DELETE FROM product_image WHERE product_id = ${sqlStr(p.id)};`);
    if (p.images.length > 0) {
      const rows = p.images.map(
        (img) => `(${sqlStr(img.id)}, ${sqlStr(p.id)}, ${sqlStr(img.url)}, ${sqlNum(img.position)})`
      );
      sql.push(`INSERT INTO product_image (id, product_id, url, position) VALUES\n  ${rows.join(",\n  ")};`);
    }

    if (p.reviews.length > 0) {
      for (const r of p.reviews) {
        sql.push(
          `INSERT IGNORE INTO review (id, product_id, author_name, rating, comment, created_at) VALUES (${sqlStr(r.id)}, ${sqlStr(p.id)}, ${sqlStr(r.authorName)}, ${sqlNum(r.rating)}, ${sqlStr(r.comment)}, ${sqlStr(r.createdAt.toISOString().slice(0, 19).replace("T", " "))});`
        );
      }
    }
    sql.push("");
  }

  sql.push("SET FOREIGN_KEY_CHECKS = 1;");

  fs.writeFileSync(OUT_SQL, sql.join("\n"), "utf8");
  console.log(`Exported ${categories.length} categories, ${products.length} products.`);
  console.log(`MySQL file written to: ${OUT_SQL}`);
  console.log("Import it via cPanel -> phpMyAdmin -> your database -> Import (after schema.sql).");
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
